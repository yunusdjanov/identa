import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

const root = process.cwd();
const sourceDir = path.join(root, 'public', 'identa-handoff');
const outFile = path.join(sourceDir, 'landing.bundle.js');
const sources = ['i18n.jsx', 'components.jsx', 'app.jsx'];

const banner = `// Generated by scripts/build-landing-handoff.mjs. Do not edit directly.\n`;

const output = sources.map((file) => {
  const source = fs.readFileSync(path.join(sourceDir, file), 'utf8');
  const result = ts.transpileModule(source, {
    compilerOptions: {
      jsx: ts.JsxEmit.React,
      module: ts.ModuleKind.None,
      target: ts.ScriptTarget.ES2018,
      removeComments: false,
    },
    fileName: file,
  });

  return `\n// ===== ${file} =====\n(() => {\n${result.outputText}\n})();`;
}).join('\n');

fs.writeFileSync(outFile, `${banner}${output}`, 'utf8');
console.log(`Built ${path.relative(root, outFile)}`);
